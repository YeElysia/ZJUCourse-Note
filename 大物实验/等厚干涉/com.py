_lambda = 589.3e-3  # m

for l in data1:
    n = l[0]
    d1 = l[1]
    d2 = l[2]
    D = d1 - d2
    if n > 11:
        Delta = D * D - (data1[17 - n + 6][1] - data1[17 - n + 6][2]) ** 2
        R = Delta / (24 * _lambda)
        print(f"({n}, {d1:.3f}, {d2:.3f}, {D:.3f}, {Delta:.3f}, {R:.3f}),")
    else:
        Delta = ""
        R = ""
        print(f"({n}, {d1:.3f}, {d2:.3f}, {D:.3f}, [{Delta}], [{R}]),")

